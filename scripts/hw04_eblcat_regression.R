eblcase$asian <- ifelse(eblcase$racecat == 2,1,0)
eblcase$hispanic <- ifelse(eblcase$racecat == 3,1,0)
install.packages("lmtest")
install.packages("car")
install.packages("MASS")
install.packages("lme4")
install.packages("glmnet")
install.packages("lmtest")
library(lmtest)
str(eblcase)
modelrace1 <- lm(ebl ~ les_size + black + asian + hispanic, data = eblcase)
modelrace2 <- lm(ebl ~ les_size + black + asian + hispanic +les_size:black + les_size:asian + les_size:hispanic , data = eblcase)
summary (modelrace2)
summary (modelrace1)
lmtest::lrtest(modelrace1, modelrace2)
